CREATE TYPE mood AS ENUM ('sad', 'ok', 'happy');
CREATE DOMAIN posint AS integer CHECK (VALUE > 0);
CREATE TABLE parent (id bigint NOT NULL, code text NOT NULL, PRIMARY KEY ((id) HASH), CONSTRAINT parent_code_key UNIQUE (code));
CREATE TABLE child (pid bigint NOT NULL, seq int NOT NULL, m mood NOT NULL, qty posint, tags text[],
  status text NOT NULL CHECK (status IN ('active', 'done')), amt numeric(10,2),
  total numeric GENERATED ALWAYS AS (amt * 2) STORED, rid bigint GENERATED BY DEFAULT AS IDENTITY,
  PRIMARY KEY ((pid) HASH, seq ASC), FOREIGN KEY (pid) REFERENCES parent (id));
CREATE TABLE ev (id bigint NOT NULL, ts date NOT NULL, v int, PRIMARY KEY ((id) HASH, ts ASC)) PARTITION BY RANGE (ts);
CREATE TABLE ev_q1 PARTITION OF ev FOR VALUES FROM ('2026-01-01') TO ('2026-04-01');
CREATE TABLE ev_q2 PARTITION OF ev FOR VALUES FROM ('2026-04-01') TO ('2026-07-01');
CREATE TABLE ev2 (id bigint NOT NULL, ts date NOT NULL, PRIMARY KEY ((id) HASH, ts ASC)) PARTITION BY RANGE (ts);
CREATE TABLE ev2_a PARTITION OF ev2 FOR VALUES FROM ('2026-01-01') TO ('2026-02-01');
CREATE TABLE ev2_def PARTITION OF ev2 DEFAULT;
CREATE TABLE node (id bigint NOT NULL, parent_id bigint REFERENCES node (id), lo int NOT NULL, hi int NOT NULL,
  code text NOT NULL CHECK (length(code) = 3), CHECK (lo < hi), PRIMARY KEY ((id) HASH));
CREATE TABLE loose (a int, b text CHECK (b <> 'x'));
CREATE TABLE m2 (r text NOT NULL, d date NOT NULL, id bigint NOT NULL, PRIMARY KEY ((id) HASH, r ASC, d ASC)) PARTITION BY RANGE (r, d);
CREATE TABLE m2_a PARTITION OF m2 FOR VALUES FROM ('a', '2026-01-01') TO ('a', '2027-01-01');
CREATE TABLE m2_b PARTITION OF m2 FOR VALUES FROM ('b', '2026-01-01') TO ('b', '2027-01-01');
CREATE TABLE ca (id bigint PRIMARY KEY, b_id bigint);
CREATE TABLE cb (id bigint PRIMARY KEY, a_id bigint REFERENCES ca (id));
ALTER TABLE ca ADD CONSTRAINT ca_b FOREIGN KEY (b_id) REFERENCES cb (id);
